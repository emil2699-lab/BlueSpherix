// Oggi keeps its compact layout while sharing the same selection material.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const dir = process.env.GLASS_SELECTION_ARTIFACTS || '/tmp/bluespherix-glass-selection-today';
await fs.mkdir(dir, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
const selected = loc => loc.locator('xpath=self::*[@data-glass-selection="selected"]').waitFor();
const cleared = () => page.waitForFunction(() => !document.querySelector('[data-glass-selection]'));
await page.goto(`${process.env.GLASS_SELECTION_URL || 'http://127.0.0.1:3001/'}#overview`);
await page.locator('.content[data-ice-glass=ready]').waitFor();
const period = page.getByRole('button', { name: '3M', exact: true });
await period.click(); await selected(period);
assert.equal(await period.getAttribute('aria-pressed'), 'true');
await page.locator('.today-welcome h1').click(); await cleared();
const rows = page.locator('.position-table button.table-row');
assert.equal(await rows.count(), 3);
const positive = rows.first();
await positive.click(); await selected(positive);
assert.equal(await positive.evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
const negative = rows.filter({ has: page.locator('.down') });
await negative.click(); await selected(negative);
assert.equal(await positive.getAttribute('data-glass-selection'), null);
const tint = (await negative.evaluate(el => el.style.getPropertyValue('--glass-control-tint'))).split(' ').map(Number);
assert(tint[0] > tint[1] * 1.5 && tint[0] > tint[2] * 1.5);
assert.equal(await negative.evaluate(el => getComputedStyle(el).boxShadow), 'none');
await page.screenshot({ path: `${dir}/today-negative.png` });
await page.keyboard.press('Escape'); await cleared();
await positive.focus(); await page.keyboard.press('Space'); await selected(positive);
await page.locator('.today-welcome h1').click(); await cleared();
await page.setViewportSize({ width: 390, height: 844 });
await negative.click(); await selected(negative);
assert(await negative.evaluate(el => el.getBoundingClientRect().height >= 44));
assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
await page.screenshot({ path: `${dir}/today-mobile.png` });
// Return through the real navigation; no stale selection from the hidden Oggi DOM.
await page.setViewportSize({ width: 1440, height: 1000 });
await page.locator('nav').getByRole('button', { name: 'Diario', exact: true }).click(); await cleared();
const journal = page.getByRole('button', { name: '90G', exact: true }); await journal.click(); await selected(journal);
await page.locator('nav').getByRole('button', { name: 'Oggi', exact: true }).click(); await cleared();
await period.click(); await selected(period);
assert.equal(await page.locator('canvas').count(), 1); assert.deepEqual(errors, []);
await fs.writeFile(`${dir}/checks.json`, JSON.stringify({ pass: true, tint, errors, checks: 'period, positive/negative positions, transfer, outside, Escape, keyboard, mobile, navigation round trip, single canvas' }, null, 2));
console.log(JSON.stringify({ pass: true, tint, errors })); await browser.close();
